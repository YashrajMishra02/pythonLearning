
# Striong Methods

name = "The Hanuman is son of lord shiv and kesari"

print(name.capitalize()) # capitalize() capitalize the string

print(name.count("s")) # count('value') count the number of occurance 

print(name.find("is")) # find('value') finds the first occurance of value in string

print(name.startswith("the")) # check if it startswith value

print(name.endswith("i"))  # check if it endswith value

print(name.replace("shiv","anjani")) # replace the value with new

print(name.split(' ')) # split the stirng with value

# traversing from end to beginning
print(name[::-1])